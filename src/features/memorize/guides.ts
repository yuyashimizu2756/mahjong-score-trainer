export type GuideBlock =
  | { type: 'paragraph'; text: string }
  | { type: 'list'; items: string[]; ordered?: boolean }
  | { type: 'formula'; text: string; note?: string }
  | {
      type: 'table';
      head: string[];
      rows: string[][];
      caption?: string;
    }
  | { type: 'figure'; tiles: string; win?: string; caption: string }
  | {
      type: 'steps';
      items: { title: string; body: string }[];
    }
  | {
      type: 'callout';
      tone: 'gold' | 'jade' | 'vermilion';
      title: string;
      body: string;
    };

